#ifndef NEXT_BOARD_PROFILE_CONTRACT_H
#define NEXT_BOARD_PROFILE_CONTRACT_H
#include <stdint.h>
/** Private PS-only DDR extension; schema-5 mailbox and all PL addresses stay unchanged. */
enum { NEXT_PROFILE_DDR=0x01010000, NEXT_PROFILE_MAGIC=0x4E585450,
       NEXT_PROFILE_SCHEMA=1, NEXT_PROFILE_HEADER_WORDS=64,
       NEXT_PROFILE_FRAME_WORDS=32, NEXT_PROFILE_MAX_FRAMES=1000,
       NEXT_PROFILE_BYTES=(64+32*1000)*4 };
/** Header ticks are little-endian uint64 word pairs; all other fields are uint32. */
enum { PH_MAGIC, PH_SCHEMA, PH_STATUS, PH_COUNT, PH_CAPACITY, PH_TIMER_HZ,
       PH_MODE, PH_SCHEDULE, PH_RECORD_WORDS, PH_HEADER_WORDS, PH_RECORD_ADDRESS,
       PH_READS_PER_FEATURE, PH_PROCESS_P95=12, PH_PROCESS_P99=14,
       PH_WALL_P95=16, PH_WALL_P99=18, PH_ERROR=24, PH_FAILING_FRAME=25 };
/** Raw per-frame ticks, followed by counters; no nominal PL cycle conversion. */
enum { PF_PROCESS=0, PF_WALL=2, PF_VERIFY=4, PF_MOMENTS=6, PF_CORDIC=8,
       PF_BRIEF=10, PF_BACKEND=12, PF_CACHE=14, PF_WAIT=16, PF_CONFIG=18,
       PF_PREP=20, PF_CLOCK_CALIBRATION=22, PF_CANDIDATES=24, PF_SELECTED=25,
       PF_FEATURES=26, PF_CLOCK_READS=27, PF_INDEX=28 };
typedef char NextProfileDdrMustBeDisjoint[
    (NEXT_PROFILE_DDR>=0x01000000+512 && NEXT_PROFILE_DDR+NEXT_PROFILE_BYTES<=0x02000000)?1:-1];
#endif
