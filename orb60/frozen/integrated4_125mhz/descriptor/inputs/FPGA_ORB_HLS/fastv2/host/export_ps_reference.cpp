#include "golden.hpp"

#include <cstdint>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <vector>

/**
 * @brief Hash all image pixels in their row-major byte order.
 * @param image Independent v1.0 reference image.
 * @return FNV-1a checksum used to identify the board validation input.
 */
static uint64_t image_digest(const orb_golden::Image& image) {
    uint64_t digest = UINT64_C(14695981039346656037);
    for (uint8_t pixel : image.pixels) {
        digest = (digest ^ pixel) * UINT64_C(1099511628211);
    }
    return digest;
}

/**
 * @brief Export independent reference points and metadata for PS self-test.
 * @param argc Must be four including the program name.
 * @param argv Input PGM, generated C include, and exact reference-pixel binary.
 * @return Zero after successfully exporting all eight pyramid levels.
 */
int main(int argc, char** argv) {
    if (argc != 4) return 2;
    const int widths[8] = {960, 800, 667, 556, 463, 386, 322, 268};
    const int heights[8] = {720, 600, 500, 417, 347, 289, 241, 201};
    const int budgets[8] = {217, 181, 151, 126, 105, 87, 73, 60};
    orb_golden::Config config;
    config.threshold = 20;
    config.low_threshold = 7;
    config.dual_threshold = true;
    config.grid_top_k = 1;
    orb_golden::Image image = orb_golden::read_pgm(argv[1]);
    if (image.width != widths[0] || image.height != heights[0]) return 2;
    std::ofstream output(argv[2], std::ios::binary);
    std::ofstream pixel_output(argv[3], std::ios::binary);
    if (!output || !pixel_output) return 2;
    std::vector<orb_golden::Point> points[8];
    orb_golden::Layer layers[8];
    size_t candidate_counts[8];
    uint64_t digests[8];
    for (int level = 0; level < 8; ++level) {
        if (level != 0) image = orb_golden::resize_linear(image, widths[level], heights[level]);
        digests[level] = image_digest(image);
        pixel_output.write(reinterpret_cast<const char*>(image.pixels.data()),
                           static_cast<std::streamsize>(image.pixels.size()));
        const std::vector<orb_golden::Point> candidates = orb_golden::tiled_candidates(image, config);
        candidate_counts[level] = candidates.size();
        points[level] = orb_golden::select_grid(candidates, widths[level] - 32,
            heights[level] - 32, budgets[level], layers[level], &config);
        if (points[level].size() > 256) return 2;
    }
    output << "/* Generated by export_ps_reference.cpp from independent golden.cpp. */\n"
              "/* Included after Fastv2Summary and OrbPoint declarations. */\n";
    output << "static const uint64_t kExpectedImageDigests[8] = {\n";
    for (uint64_t digest : digests) {
        output << "    UINT64_C(0x" << std::hex << std::setw(16) << std::setfill('0')
               << digest << "),\n";
    }
    output << std::dec << "};\nstatic const Fastv2Summary kExpectedSummaries[8] = {\n";
    for (int level = 0; level < 8; ++level) {
        const int effective_width = widths[level] - 32;
        const int effective_height = heights[level] - 32;
        const int tile_cols = effective_width / 35;
        const int tile_rows = effective_height / 35;
        const auto& layer = layers[level];
        output << "    {0x00020000, 0, " << candidate_counts[level] << ", "
               << points[level].size() << ", " << layer.cell_side << ", "
               << layer.cell_cols << ", " << layer.cell_rows << ", "
               << layer.empty_cells << ", " << layer.fallback_cells << ", "
               << tile_cols << ", " << tile_rows << ", "
               << (effective_width + tile_cols - 1) / tile_cols << ", "
               << (effective_height + tile_rows - 1) / tile_rows << ", 0, 0, 0},\n";
    }
    output << "};\nstatic const OrbPoint kExpectedPoints[8][256] = {\n";
    for (const auto& level_points : points) {
        output << "    {\n";
        for (const auto& point : level_points) {
            output << "        {" << point.x << ", " << point.y << ", "
                   << point.score << ", " << point.tile << "},\n";
        }
        output << "    },\n";
    }
    output << "};\n";
    output.close();
    pixel_output.close();
    if (!output || !pixel_output) return 2;
    std::cout << "FASTV2_PS_REFERENCE_PASS levels=8 output=" << argv[2] << '\n';
    return 0;
}
