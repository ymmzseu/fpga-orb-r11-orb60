"""Compress the frozen 32-direction table after checking every quarter rotation."""
import argparse
from pathlib import Path
import re


def generate(source, output):
    text=source.read_text()
    def values(name, count):
        body=re.search(r'\b'+name+r'\s*\[[^=]+?=\s*\{(.*?)\};',text,re.S).group(1)
        body=re.sub(r'INT64_C\(([^)]+)\)',r'\1',body)
        data=list(map(int,re.findall(r'-?\d+',body)))
        if len(data)!=count: raise ValueError(f'{name}: incorrect shape')
        return data
    offsets=values('kNextBriefOffsets',32*512*2)
    umax=values('kNextUmax',16);cordic=values('kNextCordicDegrees',32)
    def point(direction, sample):
        pos=(direction*512+sample)*2
        return offsets[pos],offsets[pos+1]
    rotations=0
    for direction in range(32):
        for sample in range(512):
            x,y=point(direction%8,sample)
            for _ in range(direction//8):x,y=-y,x
            if point(direction,sample)!=(x,y):raise ValueError('Quarter rotation changes exact offsets')
            if max(abs(x),abs(y))>18:raise ValueError('Blur patch too small')
            rotations+=1
    notices=text.split('/* Generated from v1.0 constants.hpp;',1)[0]
    lines=[notices,'// Generated by generate_descriptor_rom.py; do not edit.\n#pragma once\n#include <cstdint>\n',
           '#if defined(__SYNTHESIS__) || defined(FASTV2_HLS_CSIM)\n#include <ap_int.h>\n#endif\n',
           'namespace orb60_descriptor_rom {\n',
           '#if defined(__SYNTHESIS__) || defined(FASTV2_HLS_CSIM)\ntypedef ap_uint<24> BriefPair;\n#else\ntypedef uint32_t BriefPair;\n#endif\n',
           'static const int8_t kUmax[16]={'+','.join(map(str,umax))+'};\n',
           'static const int64_t kCordic[32]={'+','.join('INT64_C('+str(v)+')' for v in cordic)+'};\n',
           'static const BriefPair kBriefPairs[2048]={\n']
    for direction in range(8):
        for bit in range(256):
            coords=point(direction,bit*2)+point(direction,bit*2+1)
            packed=sum((v&63)<<(6*i) for i,v in enumerate(coords))
            lines.append(f'UINT32_C(0x{packed:06x}),'+ ('\n' if bit%8==7 else ' '))
    lines.append('};\n}\n')
    output.write_text(''.join(lines))
    print(f'ORB60_DESCRIPTOR_ROM_PASS checked_samples={rotations} entries=2048 bits=24 max_offset=18')


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--source',type=Path,required=True);p.add_argument('--output',type=Path,required=True)
    a=p.parse_args();generate(a.source,a.output)
